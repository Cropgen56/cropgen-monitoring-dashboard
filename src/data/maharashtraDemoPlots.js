export function getMaharashtraDemoPlots() {
  const features = farms.map((f, index) => ({
    type: "Feature",
    geometry: {
      type: "Polygon",
      coordinates: [f.ring],
    },
    properties: {
      ...f.props,
      ndviSeries: NDVI_15.map((d, i) => ({
        ...d,
        "2025": d["2025"] - index * 0.02,
      })),
      waterSeries: WATER_15.map((d, i) => ({
        ...d,
        "2025": d["2025"] - index * 0.015,
      })),
    },
  }));

  return {
    type: "FeatureCollection",
    features,
  };
}

