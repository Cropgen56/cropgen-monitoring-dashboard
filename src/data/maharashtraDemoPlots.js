function rectRing(lng0, lat0, dLng, dLat) {
  return [
    [lng0, lat0],
    [lng0 + dLng, lat0],
    [lng0 + dLng, lat0 + dLat],
    [lng0, lat0 + dLat],
    [lng0, lat0],
  ];
}

